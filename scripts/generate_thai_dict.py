#!/usr/bin/env python3
"""Generate lib/ThaiWordBreak/ThaiDictData.h from ICU's thaidict.txt.

Source: https://github.com/unicode-org/icu/blob/main/icu4c/source/data/brkitr/dictionaries/thaidict.txt
License: Unicode License (see lib/ThaiWordBreak/LICENSE-ICU).

Usage: python3 scripts/generate_thai_dict.py path/to/thaidict.txt

Each Thai codepoint U+0E01-0E5B is stored as one byte (cp - 0x0E00), so a
word is a short byte string and byte order equals codepoint order. Words are
sorted and concatenated; a word's start is blockBase[i >> 8] + relOffset[i].
Words are normalized the same way ParsedText normalizes book text: sara am is
split into nikhahit + sara aa with the nikhahit moved before tone marks.
"""

import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "lib" / "ThaiWordBreak" / "ThaiDictData.h"
BLOCK_SHIFT = 8

SARA_AM, NIKHAHIT, SARA_AA = 0x0E33, 0x0E4D, 0x0E32
TONE_MARKS = range(0x0E48, 0x0E4C)


def split_sara_am(cps):
    out = []
    for cp in cps:
        if cp != SARA_AM:
            out.append(cp)
            continue
        insert_at = len(out)
        while insert_at > 0 and out[insert_at - 1] in TONE_MARKS:
            insert_at -= 1
        out.insert(insert_at, NIKHAHIT)
        out.append(SARA_AA)
    return out


def encode(word):
    cps = split_sara_am([ord(c) for c in word])
    if not cps or any(not (0x0E01 <= cp <= 0x0E5B) for cp in cps):
        return None
    return bytes(cp - 0x0E00 for cp in cps)


def main():
    src = Path(sys.argv[1])
    words = set()
    skipped = 0
    for line in src.read_text(encoding="utf-8-sig").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        encoded = encode(line.split()[0])
        if encoded is None or len(encoded) < 2 or len(encoded) > 255:
            skipped += 1
            continue
        words.add(encoded)

    ordered = sorted(words)
    blob = bytearray()
    starts = []
    for w in ordered:
        starts.append(len(blob))
        blob += w
    starts.append(len(blob))  # end sentinel

    block_bases = [starts[i] for i in range(0, len(starts), 1 << BLOCK_SHIFT)]
    rel = [s - block_bases[i >> BLOCK_SHIFT] for i, s in enumerate(starts)]
    assert max(rel) < 0x10000
    max_len = max(len(w) for w in ordered)

    def rows(values, per_line, fmt):
        items = [fmt.format(v) for v in values]
        return "\n".join("    " + ", ".join(items[i : i + per_line]) + "," for i in range(0, len(items), per_line))

    OUT.write_text(
        f"""// Generated by scripts/generate_thai_dict.py from ICU thaidict.txt. Do not edit.
// Copyright (C) 2016 and later: Unicode, Inc. and others. License: lib/ThaiWordBreak/LICENSE-ICU
#pragma once

#include <cstdint>

namespace thai::dict {{

constexpr uint32_t WORD_COUNT = {len(ordered)};
constexpr uint8_t MAX_WORD_LEN = {max_len};
constexpr uint32_t BLOCK_SHIFT = {BLOCK_SHIFT};

// Words as bytes (cp - 0x0E00), sorted, concatenated.
inline constexpr uint8_t BLOB[{len(blob)}] = {{
{rows(blob, 24, "0x{:02X}")}
}};

inline constexpr uint32_t BLOCK_BASE[{len(block_bases)}] = {{
{rows(block_bases, 12, "{}")}
}};

// Start of word i relative to BLOCK_BASE[i >> BLOCK_SHIFT]; entry WORD_COUNT is the end sentinel.
inline constexpr uint16_t REL_OFFSET[{len(rel)}] = {{
{rows(rel, 16, "{}")}
}};

}}  // namespace thai::dict
""",
        encoding="utf-8",
    )
    flash = len(blob) + 4 * len(block_bases) + 2 * len(rel)
    print(f"{len(ordered)} words, max {max_len} chars, skipped {skipped}, {flash} bytes of flash -> {OUT}")


if __name__ == "__main__":
    main()
